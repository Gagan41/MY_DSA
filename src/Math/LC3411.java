package Math;

public class LC3411 {
    public int maxLength(int[] nums) {
        int n = nums.length;
        int ans = 1;

        for (int i = 0; i < n; i++) {
            long prod = 1;
            long lcm = 1;
            long gcd = 0;

            for (int j = i; j < n; j++) {
                int nu = nums[j];

                prod *= nu;
                gcd = gcd(gcd, nu);
                lcm = lcm(lcm, nu);

                if (prod == lcm * gcd) {
                    ans = Math.max(ans, j - i + 1);
                }
            }
        }

        return ans;
    }

    private long gcd(long a, long b) {
        while (b != 0) {
            long temp = b;
            b = a % b;
            a = temp;
        }
        return a;
    }

    private long lcm(long a, long b) {
        return (a / gcd(a, b)) * b;
    }
}
